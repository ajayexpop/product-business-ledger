def j(v):
    return '; '.join(str(x) for x in v if x not in (None, '')) if isinstance(v, list) else ('' if v is None else v)


def cut(s, n=3000):
    s = s or ''
    return s if len(s) <= n else s[:n] + ' …[cut; full text in items.json]'


