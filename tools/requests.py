def build():
    cmap, comps, by_pd = client_map()
    fullc = full_comments()
    items = []
    for src in ('jira_fr', 'jira_story_open'):
        items += [jira_record(i, src, cmap, comps, by_pd, fullc) for i in jira_issues(src)]
    listed = load(os.path.join(RAW, 'fis_list.json'))['content']['nodes']
    got = fis_nodes()
    fis = []
    for n in listed:
        if n['id'] in got:
            node, com = got[n['id']]
            node = {**n, **{k: v for k, v in node.items() if v not in (None, '')}}
            fis.append(fis_record(node, com))
    # duplicate REQ ids across different pages
    by_req = defaultdict(list)
    for r in fis:
        if r['key']:
            by_req[r['key'].upper()].append(r['id'])
    def norm_title(t):
        return re.sub(r'[^a-z0-9]+', ' ', re.sub(r'^\s*\[[^\]]*\]\s*', '', t or '').lower()).strip()
    numbered = {}
    for r in fis:
        if r['pageKind'] in ('request', 'clone'):
            numbered.setdefault(norm_title(r['title']), []).append(r['id'])
    for r in fis:
        r['reqIdShared'] = [x for x in by_req.get((r['key'] or '').upper(), []) if x != r['id']]
        twins = [x for x in numbered.get(norm_title(r['title']), []) if x != r['id']]
        r['sameTitleAs'] = twins
        rej = re.search(r'\breject', r.get('decisionStatus') or '', re.I)
        reason = None
        if rej:
            reason = 'decision log: rejected'
        elif r['pageKind'] in ('template', 'other'):
            reason = 'page kind: ' + r['pageKind']
        elif r['pageKind'] == 'draft-unnumbered' and twins:
            reason = 'unnumbered draft of ' + ', '.join(twins)
        r['excluded'] = reason is not None
        r['excludedReason'] = reason
    # prior analysis (analysis/stories.json) for stories already analysed
    prior = {s['k']: s for s in load(os.path.join(ROOT, 'analysis', 'stories.json'))['stories']}
    for r in items:
        s = prior.get(r['key'])
        r['priorAnalysis'] = ({'customers': s.get('customers'), 'tiers': s.get('tiers'), 'topTier': s.get('topTier'),
                               'valueDriver': s.get('valueDriver'), 'secondaryDriver': s.get('secondaryDriver'),
                               'productArea': s.get('productArea'), 'productDomain': s.get('productDomain'),
                               'what': s.get('what'), 'why': s.get('why'), 'outcome': s.get('outcome'),
                               'source': 'analysis/stories.json'} if s else None)
    for r in fis:
        r['priorAnalysis'] = None
    allrec = items + fis
    by_key = {r['key']: r for r in items}
    # links: jira issue links, epic, FIS -> EP mentions / similar requests
    links = []
    for r in items:
        if r['epic']:
            links.append({'from': r['id'], 'to': r['epic']['key'], 'rel': 'parent', 'toInDb': r['epic']['key'] in by_key})
        for l in r['links']:
            links.append({'from': r['id'], 'to': l['key'], 'rel': l['relation'], 'toType': l['issuetype'],
                          'toInDb': l['key'] in by_key})
    for r in fis:
        for k in r['epKeysMentioned']:
            links.append({'from': r['id'], 'to': k, 'rel': 'similar' if k in r['similarEpKeys'] else 'mentions',
                          'toInDb': k in by_key})
            if k in by_key and by_key[k]['source'] == 'jira_fr':
                by_key[k]['fis'] = (by_key[k].get('fis') or []) + [r['id']]
        for x in r['reqIdShared']:
            links.append({'from': r['id'], 'to': x, 'rel': 'same REQ id', 'toInDb': True})
    # customers
    cust = defaultdict(lambda: {'token': None, 'client': None, 'basis': None, 'tier': None, 'pipedriveId': None,
                                'sources': Counter(), 'items': Counter(), 'ids': set()})
    for r in items:
        for c in r['customers']:
            k = c['client'] or c['token']
            e = cust[k]
            e['token'] = e['token'] or c['token']
            e['client'] = c['client']
            e['basis'] = e['basis'] or c['basis']
            e['tier'] = c['tier']
            e['pipedriveId'] = e['pipedriveId'] or c.get('pipedriveId')
            e['sources'][c['source']] += 1
            if r['id'] not in e['ids']:
                e['ids'].add(r['id'])
                e['items'][r['source']] += 1
    customers = sorted(({'name': k, **{x: (dict(v) if isinstance(v, Counter) else v) for x, v in e.items() if x != 'ids'},
                         'itemIds': sorted(e['ids']),
                         'itemCount': sum(e['items'].values()), 'region': None}
                        for k, e in cust.items()), key=lambda x: -x['itemCount'])
    dump(os.path.join(DB, 'items.json'), allrec)
    dump(os.path.join(DB, 'links.json'), links)
    dump(os.path.join(DB, 'customers.json'), customers)
    write_csv(allrec)
    summ = summary(allrec, customers, links)
    dump(os.path.join(DB, 'summary.json'), summ)
    print(json.dumps(summ['counts'], indent=1))


