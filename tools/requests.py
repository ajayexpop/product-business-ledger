def load(p):
    with open(p) as f:
        return json.load(f)


def dump(p, o):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w') as f:
        json.dump(o, f, indent=1, ensure_ascii=False)
        f.write('\n')


def opt(v):
    if isinstance(v, dict):
        return v.get('value') or v.get('name')
    if isinstance(v, list):
        return [opt(x) for x in v if opt(x) is not None]
    return v


def user(v):
    return v.get('displayName') if isinstance(v, dict) else None


def text(v):
    if not isinstance(v, str) or PLACEHOLDER.match(v):
        return None
    return v.strip()


