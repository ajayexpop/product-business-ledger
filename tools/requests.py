def client_map():
    m = load(os.path.join(ROOT, 'data', 'done-raw', 'client_map.json'))
    m.pop('_about', None)
    comps = {c['name']: c for c in load(os.path.join(ROOT, 'ledger', 'data', 'ledger.json'))['companies']}
    for name, c in comps.items():
        m.setdefault(name, {'client': name, 'basis': 'exact'})
        for t in c.get('deliveryTags') or []:
            m.setdefault(t, {'client': name, 'basis': 'exact'})
    by_pd = {str(c['pd']): n for n, c in comps.items() if c.get('pd')}
    return m, comps, by_pd


def resolve(token, source, cmap, comps):
    t = token.strip()
    hit = cmap.get(t) or next((v for k, v in cmap.items() if k.lower() == t.lower()), None)
    c = hit.get('client') if hit else None
    out = {'token': t, 'source': source, 'client': c, 'basis': hit['basis'] if hit else 'none',
           'tier': comps[c]['tier'] if c in comps else None}
    if c in comps:
        out['pipedriveId'] = str(comps[c].get('pd') or '') or None
    return out


