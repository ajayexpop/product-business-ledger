#!/usr/bin/env python3
"""Feedback roadmap: turns the page's feedback (Happy / Sad / Want) into docs/feedback-roadmap.md.

  python3 tools/feedback.py build     live/db/feedback -> docs/feedback-roadmap.md
  python3 tools/feedback.py check     every note has a mood, text and date; every reply points at a note

Export first (update cycle step 1), as the owner, so every person's feedback is readable:
  ArtifactData list  collection "feedback"                 out_dir live/db   -> live/db/feedback/<id>.json (one marker per person)
  ArtifactData list  collection "feedback/<id>/items"      out_dir live/db   -> live/db/feedback/<id>/items/<fid>.json
  ArtifactData list  collection "feedback/<id>/replies"    out_dir live/db   -> live/db/feedback/<id>/replies/<fid>.json
People are shown by id; resolve names with ArtifactData "profiles" when you need them (never store names)."""
import glob, json, os, sys

W = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda *a: os.path.join(W, *a)
MOOD = {'happy': 'Happy', 'sad': 'Sad', 'want': 'Want'}
STATUS = [('new', 'New'), ('planned', 'Planned'), ('building', 'Building'), ('shipped', 'Shipped'), ('wont', 'Won’t do')]
WEIGHT = {'nice': 'nice to have', 'important': 'important', 'blocking': 'blocking'}
TAB = {'overview': 'Overview', 'ledger': 'Clients', 'timeline': 'Timeline', 'pipeline': 'Requests', 'demand': 'Demand', 'delivery': 'Delivery',
       'bugs': 'Bugs', 'incidents': 'Incidents', 'logic': 'Rules', 'method': 'Method & sources', 'refresh': 'Data refresh'}


def load():
    root = J('live', 'db', 'feedback'); notes = []
    for uid in sorted(d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d))) if os.path.isdir(root) else []:
        reps = {os.path.basename(f)[:-5]: json.load(open(f)) for f in glob.glob(os.path.join(root, uid, 'replies', '*.json'))}
        for f in glob.glob(os.path.join(root, uid, 'items', '*.json')):
            fid = os.path.basename(f)[:-5]; n = json.load(open(f)); r = reps.get(fid, {})
            notes.append(dict(n, id=fid, uid=uid, status=r.get('status') or 'new', theme=r.get('theme') or '', msgs=r.get('msgs') or []))
        for fid in reps:
            if not os.path.exists(os.path.join(root, uid, 'items', fid + '.json')): notes.append({'id': fid, 'uid': uid, 'orphan': True})
    return notes


def where(n):
    w = n.get('where') or {}
    return (TAB.get(w.get('tab'), w.get('tab') or '') + (' › ' + w['pop'] if w.get('pop') else '')) or '—'


def build():
    notes = [n for n in load() if not n.get('orphan')]; notes.sort(key=lambda n: n.get('at', ''), reverse=True)
    people = len({n['uid'] for n in notes})
    L = ['# Feedback roadmap', '',
         'Generated by `python3 tools/feedback.py build` from `live/db/feedback` (the page\'s Happy / Sad / Want feedback). Private to Ajay: do not publish or share.', '',
         f'{len(notes)} notes from {people} {"person" if people == 1 else "people"}: ' + ', '.join(f'{sum(n.get("mood") == k for n in notes)} {v}' for k, v in MOOD.items()) + '.', '']
    for st, label in STATUS:
        group = [n for n in notes if n['status'] == st]
        if not group: continue
        L += [f'## {label} ({len(group)})', '']
        themes = {}
        for n in group: themes.setdefault(n['theme'] or '', []).append(n)
        for th in sorted(themes, key=lambda t: (t == '', -len(themes[t]), t)):
            ns = themes[th]
            L.append(f'### {th} — {len(ns)} note{"s" if len(ns) != 1 else ""}, {len({n["uid"] for n in ns})} people' if th else '### No theme yet')
            L.append('')
            for n in ns:
                w = WEIGHT.get(n.get('weight'), '')
                L.append(f'- **{MOOD.get(n.get("mood"), n.get("mood"))}** · {n.get("at", "")[:10]} · {where(n)}{" · " + w if w else ""} · `{n["uid"]}`  ')
                L.append('  ' + str(n.get('text', '')).replace('\n', ' '))
                for m in n['msgs']: L.append(f'  - Reply {str(m.get("at", ""))[:10]}: {m.get("text", "")}')
            L.append('')
    if not notes: L += ['No feedback yet.', '']
    open(J('docs', 'feedback-roadmap.md'), 'w').write('\n'.join(L))
    print(f'docs/feedback-roadmap.md: {len(notes)} notes, {people} people')


def check():
    bad = []
    for n in load():
        if n.get('orphan'): bad.append(f'reply without a note: {n["uid"]}/{n["id"]}'); continue
        for k in ('mood', 'text', 'at', 'by'):
            if not n.get(k): bad.append(f'{n["uid"]}/{n["id"]}: no {k}')
        if n.get('by') and n['by'] != n['uid']: bad.append(f'{n["uid"]}/{n["id"]}: written by {n["by"]}, not the folder owner')
        if n.get('mood') and n['mood'] not in MOOD: bad.append(f'{n["uid"]}/{n["id"]}: unknown mood {n["mood"]}')
    print('\n'.join(bad) or 'feedback: PASS'); return not bad


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'build'
    if cmd == 'build': build()
    elif cmd == 'check': sys.exit(0 if check() else 1)
    else: print(__doc__); sys.exit(2)
