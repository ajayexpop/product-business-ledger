    gate('stories are all type Story, status Open', all(r['issueType'] == 'Story' and r['status'] == 'Open'
                                                         for r in by['jira_story_open']))
    gate('no bugs or defects', not [r for r in recs if (r.get('issueType') or '') in ('Bug', 'Defect')])
    short = [r['id'] for r in recs if r['source'] != 'fis' and len(r['comments']) < r['commentCount']]
    gate('every Jira comment thread complete', not short, short[:10])
    gate('every FIS page listed was fetched', len(by['fis']) == len(listed),
         f"{len(by['fis'])} of {len(listed)}; missing {[n['id'] for n in listed if 'FIS-' + n['id'] not in ids][:10]}")
    nocom = [n['id'] for n in listed if not os.path.exists(os.path.join(RAW, 'fis_pages', n['id'] + '.comments.json'))]
    gate('every FIS page has its footer comments file', not nocom, nocom[:10])
    empty = [r['id'] for r in by['fis'] if not r['excluded'] and len(r['body']) < 200]
    gate('in-scope FIS pages have a body', not empty, empty[:10])
    gate('in-scope FIS pages have a REQ id', all(r['key'] for r in by['fis'] if not r['excluded']))
    unparsed = [r['id'] for r in by['fis'] if not r['excluded'] and r['aiAnalysed'] and not r['scoresParsed']]
    gate('analysed FIS pages have a parsed Total Opportunity', not unparsed, unparsed)
    rej = [r['id'] for r in by['fis'] if not r['excluded'] and re.search(r'\breject', r.get('decisionStatus') or '', re.I)]
    gate('no rejected FIS requests in scope', not rej, rej)
    dang = [l for l in links if l['from'] not in set(ids)]
    gate('every link starts at a record', not dang, len(dang))
    reserved = [r['id'] for r in recs if any(r.get(k) is not None for k in RESERVED)]
    gate('theming fields reserved (empty)', not reserved, len(reserved))
