def adf_text(n, out=None, depth=0):
    """ADF -> markdown-ish text: paragraphs/headings on their own line, table rows as | a | b |."""
    if out is None:
        out = []
    if isinstance(n, list):
        for x in n:
            adf_text(x, out, depth)
        return out
    if not isinstance(n, dict):
        return out
    t = n.get('type')
    if t == 'text':
        out.append(n.get('text', ''))
    elif t in ('hardBreak',):
        out.append('\n')
    elif t == 'mention':
        out.append((n.get('attrs') or {}).get('text', ''))
    elif t in ('inlineCard', 'blockCard', 'embedCard'):
        out.append((n.get('attrs') or {}).get('url', ''))
    elif t == 'emoji':
        out.append((n.get('attrs') or {}).get('text', ''))
    elif t == 'status':
        out.append('[' + (n.get('attrs') or {}).get('text', '') + ']')
    elif t == 'date':
        out.append((n.get('attrs') or {}).get('timestamp', ''))
    elif t == 'tableRow':
        cells = [''.join(adf_text(c.get('content') or [], [], depth)).strip().replace('\n', ' ')
                 for c in n.get('content') or []]
        out.append('\n| ' + ' | '.join(cells) + ' |')
    elif t == 'heading':
        out.append('\n' + '#' * ((n.get('attrs') or {}).get('level', 2)) + ' ')
        adf_text(n.get('content') or [], out, depth)
        out.append('\n')
    elif t == 'listItem':
        out.append('\n' + '  ' * depth + '- ')
        adf_text(n.get('content') or [], out, depth + 1)
    elif t in ('paragraph', 'blockquote', 'codeBlock', 'panel', 'expand', 'nestedExpand', 'decisionItem', 'taskItem'):
        out.append('\n')
        if t in ('expand', 'nestedExpand') and (n.get('attrs') or {}).get('title'):
            out.append('## ' + n['attrs']['title'] + '\n')
        adf_text(n.get('content') or [], out, depth)
        out.append('\n')
    else:
        adf_text(n.get('content') or [], out, depth)
    return out


def page_text(node):
    b = node.get('body')
    if isinstance(b, dict):
        s = ''.join(adf_text(b))
    else:
        s = b or ''
    s = re.sub(r'[ \t]+\n', '\n', s)
    return re.sub(r'\n{3,}', '\n\n', s).strip()


REQ_ID = re.compile(r'REQ-(\d{4}|YYYY)-(\d{3}|NNN)(?:-(?:cloned|CLONE|Cloned))?', re.I)
EP_KEY = re.compile(r'\bEP-\d{2,6}\b')


def table_value(txt, label):
    m = re.search(r'^\|\s*\**' + re.escape(label) + r'\**\s*\|\s*(.*?)\s*\|\s*$', txt, re.M | re.I)
    return m.group(1).strip() if m else None


def after(txt, pattern, flags=re.I):
    m = re.search(pattern, txt, flags)
    return m.group(1).strip() if m else None


def num(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None


HEAD = re.compile(r'^\s*(#{1,6})\s+|^\s*h([1-6])\.\s+')
MARKER = re.compile(r'^\s*(?:#{1,6}\s+|h\d\.\s+)?\S*\s*(?:\d️⃣|🤖|📋|📝|💬)')   # "2️⃣ Problem Statement", "🤖 AI Analysis"


def level(line):
    m = HEAD.match(line)
    if m:
        return len(m.group(1)) if m.group(1) else int(m.group(2))
    return 2 if MARKER.match(line) and len(line) < 80 else None


def section(txt, *titles):
    """Text under the heading (or emoji marker line) naming any of `titles`, up to the next heading of the same
    level or higher. Pages mix '## x', 'h2. x' and bare '2️⃣ x' lines, so this scans lines, not markup."""
    lines = txt.splitlines()
    for t in titles:
        for i, l in enumerate(lines):
            lv = level(l)
            if lv is None or t.lower() not in l.lower():
                continue
            body = []
            for x in lines[i + 1:]:
                xl = level(x)
                if xl is not None and xl <= lv:
                    break
                body.append(x)
            s = '\n'.join(body).strip().strip('-').strip()
            if s:
                return s
    return None


def score(txt, *labels):
    """First number stated for a score: 'X Score: 4.2/5', '### X Score: 215', 'X: **3.0**', or a formula line
    '= 1.2 + 1.6 = 2.8' / 'Total ... (36)' within the few lines after the heading."""
    for lab in labels:
        m = re.search(re.escape(lab) + r'\**\s*[:=]\s*\**\s*~?([\d.]+)', txt, re.I)
        if m and num(m.group(1)) is not None:
            return num(m.group(1))
        m = re.search(r'^[^\n]*' + re.escape(lab) + r'[^\n]*\n((?:[^\n]*\n){0,8})', txt, re.I | re.M)
        if m:
            blk = m.group(1)
            for p in (r'(?:Score|Total|Result|Final)\**\s*[:=]\s*\**\s*~?([\d.]+)', r'=\s*\**\s*~?([\d.]+)\**\s*(?:/\s*\d+)?\s*(?:\(|$|\n)',
                      r'\((\d+(?:\.\d+)?)\)'):
                ms = re.findall(p, blk, re.M)
                if ms and num(ms[-1]) is not None:
                    return num(ms[-1])
    return None


def fis_record(node, comments):
    txt = page_text(node)
    title = node.get('title') or ''
    rid = REQ_ID.search(title) or REQ_ID.search(table_value(txt, 'Request ID') or '')
    req_id = rid.group(0) if rid else None
    tag = re.match(r'^\s*\[([^\]]+)\]', title)
    tag = tag.group(1) if tag else ''
    if title.upper().startswith('[TEMPLATE]'):
        kind = 'template'
    elif re.search(r'-?clone', tag, re.I):                    # [REQ-2026-034-cloned], [REQ-2026-013-CLONE]
        kind = 'clone'
    elif req_id and re.search(r'YYYY|NNN', req_id, re.I):
        kind = 'draft-unnumbered'
    elif req_id:
        kind = 'request'
    else:
        kind = 'other'
    decision = section(txt, 'Decision Log')
    dec_status = None
    if decision:
        rows = [l for l in decision.splitlines() if l.strip() and not re.match(r'^\|?\s*-{3}', l.strip())]
        first = rows[0].strip() if rows else ''
        if first.startswith('|') and re.search(r'\|\s*Date\s*\|', first, re.I):   # a table: take its first data row
            first = rows[1].strip() if len(rows) > 1 else ''
        dec_status = re.sub(r'[*_#]', '', first).strip(' -|')[:160] or None
    classification = after(txt, r'Recommended (?:Classification|Priority)\**:?\**\s*[^\w\n]*\s*(NOW|NEXT|LATER|QUICK WIN|TBD)\b')
    scores = {
        'frequency': score(txt, 'Frequency Score'),
        'businessImpact': score(txt, 'Business Impact Score'),
        'urgency': score(txt, 'Urgency Score'),
        'sponsorMultiplier': score(txt, 'Sponsor Multiplier'),
        'totalOpportunity': score(txt, 'Total Opportunity Score', 'Total Opportunity'),
        'glossaryCompliance': score(txt, 'Compliance Score'),
        'problemClarity': num(after(txt, r'Problem Clarity Score[^\n]*\n+\s*\**Score\**:?\s*([\d.]+)')),
        'evidenceQuality': num(after(txt, r'Evidence Quality Score[^\n]*\n+\s*\**Score\**:?\s*([\d.]+)')),
    }
    analysis_state = (meta_status := table_value(txt, 'AI Analysis Date') or '')
    analysed = bool(re.search(r'Frequency Score|Total Opportunity', txt, re.I)) and \
        not re.search(r'not yet analy', analysis_state, re.I) or scores['totalOpportunity'] is not None
    effort = after(txt, r'Estimated Effort[^\n]*\n+\s*\**Level\**:?\s*[^\w\n]*\s*([^\n]+)')
    percentile = after(txt, r'Percentile Rank:?\s*([^\n]+)')
    impacted = after(txt, r'Event\(s\) Impacted\**:?\**\s*([^\n]+)')
    ep_keys = sorted(set(EP_KEY.findall(txt)), key=lambda k: int(k.split('-')[1]))
    dup = section(txt, 'Similar Requests')
    dup_keys = sorted(set(EP_KEY.findall(dup or '')), key=lambda k: int(k.split('-')[1]))
    evidence = section(txt, 'Evidence Pack')
    problem = section(txt, 'Problem Statement')
    webui = (node.get('_links') or {}).get('webui') or ''
    meta = {k: table_value(txt, k) for k in
            ('Request ID', 'Created Date', 'Created By', 'Product Area', 'Priority Score', 'Effort Estimate',
             'Status', 'AI Analysis Date', 'Productboard Link')}
    return {
        'id': 'FIS-' + node['id'], 'source': 'fis', 'key': req_id, 'pageId': node['id'],
        'link': node.get('webUrl') or (WIKI + webui if webui else None),
        'pageKind': kind,
        'title': title,
        'status': meta.get('Status') or node.get('status'),
        'created': meta.get('Created Date'), 'updated': node.get('lastModified'),
        'author': (node.get('author') or {}).get('displayName'),
        'createdBy': (meta.get('Created By') or '').strip('[]\\ ') or None,
        'fisProductArea': meta.get('Product Area'),
        'priorityScoreField': meta.get('Priority Score'), 'effortEstimateField': meta.get('Effort Estimate'),
        'eventsImpacted': impacted,
        'problemStatement': problem,
        'evidencePack': evidence,
        'aiAnalysed': analysed,
        'scores': scores,
        'scoresParsed': scores['totalOpportunity'] is not None,
        'percentileRank': percentile,
        'estimatedEffort': effort,
        'recommendedClassification': classification,
        'decisionLog': decision, 'decisionStatus': dec_status,
        'epKeysMentioned': ep_keys, 'similarEpKeys': dup_keys,
        'customers': [],               # names are free text on FIS pages; resolved in the theming phase
        'body': txt,
        'commentCount': len(comments),
        'comments': comments,
        **RESERVED,
    }


def fis_nodes():
    """raw/fis_pages/<id>.json (adf) or <id>.md.json (markdown) -> {id: (node, comments)}."""
    out = {}
    for p in sorted(glob.glob(os.path.join(RAW, 'fis_pages', '*.json'))):
        b = os.path.basename(p)
        if b.endswith('.comments.json'):
            continue
        pid = b.split('.')[0]
        d = load(p)
        nodes = (d.get('content') or {}).get('nodes') or d.get('nodes') or ([d] if d.get('id') else [])
        if not nodes:
            continue
        node = nodes[0]
        cp = os.path.join(RAW, 'fis_pages', pid + '.comments.json')
        comments = []
        if os.path.exists(cp):
            comments = fis_comments(load(cp))
        out[pid] = (node, comments)
    return out


def fis_comments(d):
    items = []
    stack = [d]
    while stack:                                    # tolerate the shapes the tool returns
        x = stack.pop()
        if isinstance(x, dict):
            if 'body' in x and ('id' in x) and ('author' in x or 'version' in x or 'created' in x or 'createdAt' in x):
                b = x['body']
                if isinstance(b, dict):
                    b = ''.join(adf_text(b.get('atlas_doc_format') or b.get('value') or b)) if not isinstance(
                        b.get('storage'), dict) else b['storage'].get('value')
                items.append({'id': x.get('id'),
                              'author': (x.get('author') or {}).get('displayName') if isinstance(x.get('author'), dict) else x.get('authorId'),
                              'created': x.get('created') or x.get('createdAt') or (x.get('version') or {}).get('createdAt'),
                              'body': (b or '').strip() if isinstance(b, str) else json.dumps(b)})
            else:
                stack.extend(x.values())
        elif isinstance(x, list):
            stack.extend(x)
    return sorted(items, key=lambda c: str(c.get('created')))


