def summary(recs, customers, links):
    def cnt(rs, f):
        return Counter(f(r) for r in rs).most_common()
    jf = [r for r in recs if r['source'] == 'jira_fr']
    js = [r for r in recs if r['source'] == 'jira_story_open']
    fi = [r for r in recs if r['source'] == 'fis']
    return {
        'asOf': '2026-09-26',
        'counts': {'jira_fr': len(jf), 'jira_story_open': len(js), 'fis_pages': len(fi),
                   'fis_in_scope': sum(not r['excluded'] for r in fi),
                   'comments': sum(len(r['comments']) for r in recs), 'links': len(links),
                   'customers': len(customers),
                   'ledger_matched_customers': sum(1 for c in customers if c['client'])},
        'fr_by_status': cnt(jf, lambda r: r['status']),
        'fr_by_team': cnt(jf, lambda r: r['team']),
        'story_by_team': cnt(js, lambda r: r['team']),
        'fr_by_request_type': cnt(jf, lambda r: r['requestType']),
        'fr_by_rgto': cnt(jf, lambda r: r['rgto']),
        'components': Counter(c for r in jf + js for c in r['components']).most_common(),
        'fis_by_kind': cnt(fi, lambda r: r['pageKind']),
        'fis_by_classification': cnt([r for r in fi if not r['excluded']], lambda r: r['recommendedClassification']),
        'fis_by_product_area': cnt([r for r in fi if not r['excluded']], lambda r: r['fisProductArea']),
        'items_with_ledger_customer': sum(1 for r in jf + js if any(c['client'] for c in r['customers'])),
        'items_with_any_customer_token': sum(1 for r in jf + js if r['customers']),
        'stories_with_prior_analysis': sum(1 for r in js if r['priorAnalysis']),
        'top_customers': [(c['name'], c['itemCount'], c['tier']) for c in customers[:40]],
    }


