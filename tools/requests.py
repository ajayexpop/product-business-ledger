    for name, ok, d in gates:
        print(('PASS ' if ok else 'FAIL ') + name + (f'  [{d}]' if d not in ('', None) and not ok else ''))
        fail += not ok
    print(f'{len(gates) - fail}/{len(gates)} PASS')
    sys.exit(1 if fail else 0)


